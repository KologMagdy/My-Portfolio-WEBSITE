// Generates ../../theme.css — Material 3 color roles (light + dark) for every seed
// color, using Google's official Material Color Utilities (Tonal Spot scheme).
//
//   cd tools/theme && npm install && npm run build
//
// Edit SEEDS below to change the palettes offered by the site's color picker.
// The first seed is the default one.
import fs from 'node:fs';
import path from 'node:path';
import {
  Hct, SchemeTonalSpot, MaterialDynamicColors, hexFromArgb, argbFromHex,
} from '@material/material-color-utilities';

const SEEDS = {
  violet: '#6750A4',
  blue: '#1A73E8',
  green: '#1E8E3E',
  orange: '#E8710A',
  rose: '#D93F87',
};

const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'surface', 'onSurface', 'onSurfaceVariant', 'surfaceDim', 'surfaceBright',
  'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest',
  'outline', 'outlineVariant', 'inverseSurface', 'inverseOnSurface', 'inversePrimary',
  'scrim', 'shadow',
];

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());

function roles(hex, isDark) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(hex)), isDark, 0);
  return ROLES.map((r) => `  --md-sys-color-${kebab(r)}: ${hexFromArgb(MaterialDynamicColors[r].getArgb(scheme))};`).join('\n');
}

const names = Object.keys(SEEDS);
const sel = (name, extra = '') => {
  const base = `:root[data-seed="${name}"]${extra}`;
  // Default seed also applies when no data-seed is set (e.g. JS disabled).
  return name === names[0] ? `${base},\n:root:not([data-seed])${extra}` : base;
};

let css = `/* AUTO-GENERATED by tools/theme/generate-theme.mjs — do not edit by hand. */\n`;
css += `/* Material 3 color roles · Tonal Spot · seeds: ${names.map((n) => `${n} ${SEEDS[n]}`).join(', ')} */\n\n`;
css += `:root { color-scheme: light; }\n:root[data-theme="dark"] { color-scheme: dark; }\n`;
css += `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) { color-scheme: dark; }\n}\n\n`;

for (const name of names) {
  css += `/* ── ${name} ── */\n`;
  css += `${sel(name)} {\n${roles(SEEDS[name], false)}\n}\n`;
  css += `@media (prefers-color-scheme: dark) {\n${sel(name, ':not([data-theme="light"])')} {\n${roles(SEEDS[name], true)}\n}\n}\n`;
  css += `${sel(name, '[data-theme="dark"]')} {\n${roles(SEEDS[name], true)}\n}\n\n`;
}

// Run from tools/theme (npm run build); writes to the repository root.
const out = path.resolve(process.cwd(), '../../theme.css');
fs.writeFileSync(out, css);
console.log(`Wrote ${out}`);
